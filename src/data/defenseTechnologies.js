const titleFromId = (id) =>
  id
    .split('-')
    .map((part) => part.toUpperCase())
    .join(' ');

const categoryByKeyword = (id) => {
  if (id.includes('ship') || id.includes('submarine') || id.includes('sonar') || id.includes('naval')) return 'naval';
  if (id.includes('missile') || id.includes('munition') || id.includes('shell') || id.includes('warhead')) return 'missile';
  if (id.includes('air') || id.includes('turbofan') || id.includes('helicopter') || id.includes('fly')) return 'aerospace';
  if (id.includes('network') || id.includes('communication') || id.includes('eo') || id.includes('radar')) return 'electronics';
  if (id.includes('space') || id.includes('cyber')) return 'cyber';
  if (id.includes('vehicle') || id.includes('tank') || id.includes('protection') || id.includes('fire-control')) return 'land';
  return 'prime';
};


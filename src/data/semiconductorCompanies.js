const normalizeCompany = (company) => {
  const segments = [...new Set((company.segments || []).map(normalizeSegment))];
  return {
    ...company,
    segments,
    logo: LOCAL_LOGOS[company.id] || company.logo || null,
    logoUrl: getLogoUrl(company),
    accentColor: company.accentColor || SEGMENT_ACCENT[segments[0]] || 'blue',
  };
};

